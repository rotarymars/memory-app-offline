// SHA-256 for image names and duplicate detection. Uses Web Crypto when it's
// there; crypto.subtle only exists on https:// and localhost, so opening the
// app over plain http on a LAN address falls back to the small pure-JS
// version below.

const encoder = new TextEncoder();

/**
 * @param {Uint8Array | ArrayBuffer | string} data
 * @returns {Promise<string>} lowercase hex
 */
export async function sha256Hex(data) {
  const bytes = toBytes(data);
  const subtle = globalThis.crypto?.subtle;
  if (subtle) {
    try {
      const digest = await subtle.digest("SHA-256", bytes);
      return toHex(new Uint8Array(digest));
    } catch {
      // Fall through to the pure-JS version.
    }
  }
  return sha256HexSync(bytes);
}

function toBytes(data) {
  if (typeof data === "string") return encoder.encode(data);
  if (data instanceof Uint8Array) return data;
  if (data instanceof ArrayBuffer) return new Uint8Array(data);
  throw new TypeError("sha256Hex expects a string, Uint8Array or ArrayBuffer");
}

function toHex(bytes) {
  let out = "";
  for (const b of bytes) out += b.toString(16).padStart(2, "0");
  return out;
}

